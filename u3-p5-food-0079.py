import pandas as pd
import matplotlib.pyplot as plt
# Iram Jimenez NC = 0079
# 4. Leer el archivo CSV desde el archivo de indian food
df_food_india = pd.read_csv('indian_food.csv')
print("\n--- DATOS LEÍDOS DESDE CSV Iram Jimenez 0079 ---")
print(df_food_india)
print("\n--- Mostrar nombre de comida mas ingredientes Iram Jimenez 0079 ---")
recetas = df_food_india[['name', 'ingredients']]
print(recetas)
print("\n--- Tiempo de cocinado mostrar los primeros 10 registros Iram Jimenez 0079 ---")
nombre_y_tiempo = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y_tiempo)
print("\n--- Grafica comida (X) Tiempo de cocinado (Y) Iram Jimenez 0079 ---")
print("\n--- Grafica comida (X) Texto a 30 grados Iram Jimenez 0079 ---")
nombre_y_tiempo.plot.bar(x='name',y='cook_time', rot=30)
plt.title('Comida tipica de India Iram Jimenez NC = 0079')
plt.xlabel('Nombre del platillo')
plt.ylabel('Tiempo de coccion')
plt.show()
nombre_y_tiempo = df_food_india[['name', 'prep_time', 'cook_time']].head(10)
nombre_y_tiempo.plot.bar(x='name', rot=30)
plt.title('Grafica de 2 columnas Iram Jimenez NC = 0079')  
plt.xlabel('Nombre del platillo')
plt.ylabel('Tiempo de coccion')
plt.show()
print("\n--- Graficas apiladas verticalmente una tras otra Iram Jimenez 0079 ---")
nombre_y_tiempo.plot.bar(x='name', stacked=True, rot=30)
plt.title('Grafica apiladas Iram Jimenez NC = 0079')  
plt.xlabel('Nombre del platillo')
plt.ylabel('Tiempo de coccion')
plt.show()